"""Generate reference test vectors in tests/data/ using ERFA (pyerfa) and friends.

Dev-only: requires numpy, pyerfa (and for later sections sgp4, jplephem).
Usage:  python3 tools/gen_reference.py [section ...]
Sections: time (default: all)

The generated CSV files are committed; the C++ tests read them, so this script
is only re-run when adding cases.
"""
import os
import random
import sys

import erfa
import numpy as np

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "data")


def write_csv(name, header, rows, comment):
    path = os.path.join(OUT, name)
    with open(path, "w") as f:
        f.write(f"# {comment}\n# Generated by tools/gen_reference.py with pyerfa {erfa.__version__}\n")
        f.write(",".join(header) + "\n")
        for r in rows:
            f.write(",".join(repr(float(x)) if not isinstance(x, (int, str)) else str(x) for x in r) + "\n")
    print(f"wrote {path} ({len(rows)} rows)")


def time_section():
    rng = random.Random(12345)
    cases = []
    # Random epochs 1960-2035 plus leap-second-day edge cases.
    for _ in range(300):
        y = rng.randint(1960, 2035)
        m = rng.randint(1, 12)
        d = rng.randint(1, 28)
        cases.append((y, m, d, rng.randint(0, 23), rng.randint(0, 59), round(rng.uniform(0, 59.999999), 6)))
    for (y, m, d) in [(2016, 12, 31), (2015, 6, 30), (1972, 6, 30), (1998, 12, 31), (1961, 7, 31), (1968, 1, 31)]:
        cases += [(y, m, d, 23, 59, 59.5), (y, m, d, 0, 0, 0.0), (y, m, d, 12, 0, 0.0)]
    cases += [(2016, 12, 31, 23, 59, 60.0), (2016, 12, 31, 23, 59, 60.75), (2015, 6, 30, 23, 59, 60.25)]
    dut1 = 0.1234567
    rows = []
    for (y, m, d, h, mi, s) in cases:
        u1, u2 = erfa.dtf2d("UTC", y, m, d, h, mi, s)
        a1, a2 = erfa.utctai(u1, u2)
        t1, t2 = erfa.taitt(a1, a2)
        dtr = erfa.dtdb(t1, t2, 0.0, 0.0, 0.0, 0.0)
        b1, b2 = erfa.tttdb(t1, t2, dtr)
        g1, g2 = erfa.tttcg(t1, t2)
        c1, c2 = erfa.tdbtcb(b1, b2)
        r1, r2 = erfa.utcut1(u1, u2, dut1)
        rows.append((y, m, d, h, mi, s, u1, u2, a1, a2, t1, t2, b1, b2, g1, g2, c1, c2, r1, r2, dtr))
    header = ["year", "month", "day", "hour", "minute", "second", "utc1", "utc2", "tai1", "tai2", "tt1", "tt2",
              "tdb1", "tdb2", "tcg1", "tcg2", "tcb1", "tcb2", "ut11", "ut12", "tdb_minus_tt"]
    write_csv("time_scales.csv", header, rows, f"UTC calendar -> scales via ERFA; UT1 uses dut1={dut1} s")

    # Topocentric TDB-TT.
    rows = []
    for _ in range(50):
        jd = 2451545.0 + rng.uniform(-36525, 36525)
        ut = rng.uniform(0, 1)
        elong = rng.uniform(-np.pi, np.pi)
        u = rng.uniform(0, 6378.0)
        v = rng.uniform(-6357.0, 6357.0)
        rows.append((jd, ut, elong, u, v, erfa.dtdb(jd, 0.0, ut, elong, u, v)))
    write_csv("dtdb_topo.csv", ["jd_tt", "ut", "elong", "u_km", "v_km", "dtdb"], rows, "ERFA dtdb with topocentric terms")


def geodesy_section():
    rng = random.Random(777)
    rows = []
    for i in range(400):
        lat = rng.uniform(-np.pi / 2, np.pi / 2)
        if i < 10:
            lat = [np.pi / 2, -np.pi / 2, 0.0, 1e-12, -1e-12, np.pi / 2 - 1e-10, 0.5, -0.5, 1.2, -1.2][i]
        lon = rng.uniform(-np.pi, np.pi)
        h = rng.choice([rng.uniform(-1e4, 1e4), rng.uniform(1e4, 4e7), rng.uniform(-6.3e6, -1e5), rng.uniform(0, 1e3)])
        xyz = erfa.gd2gc(1, lon, lat, h)
        e, p, hh = erfa.gc2gd(1, xyz)
        rows.append((lat, lon, h, xyz[0], xyz[1], xyz[2], p, e, hh))
    write_csv("geodetic.csv", ["lat", "lon", "h", "x", "y", "z", "lat_erfa", "lon_erfa", "h_erfa"], rows,
              "WGS84 geodetic<->ECEF via ERFA gd2gc/gc2gd")


def frames_section():
    rng = random.Random(2024)
    rows = []
    for i in range(60):
        # TT and UT1 two-part dates spanning 1900-2100.
        tt1 = 2451545.0 + float(rng.randint(-36500, 36500)) - 0.5
        tt2 = rng.uniform(0, 1)
        ut2 = tt2 - rng.uniform(60, 70) / 86400.0
        xp = rng.uniform(-0.3, 0.3) * erfa.DAS2R
        yp = rng.uniform(0, 0.6) * erfa.DAS2R
        dx = rng.uniform(-0.3, 0.3) * erfa.DMAS2R
        dy = rng.uniform(-0.3, 0.3) * erfa.DMAS2R
        x, y = erfa.xy06(tt1, tt2)
        s = erfa.s06(tt1, tt2, x, y)
        rc2i = erfa.c2ixys(x + dx, y + dy, s)
        era = erfa.era00(tt1, ut2)
        sp = erfa.sp00(tt1, tt2)
        rpom = erfa.pom00(xp, yp, sp)
        rc2t = erfa.c2tcio(rc2i, era, rpom)
        dpsi, deps = erfa.nut06a(tt1, tt2)
        dpsib, depsb = erfa.nut00b(tt1, tt2)
        rb, rp, rbp = erfa.bp06(tt1, tt2)
        rnpb = erfa.pnm06a(tt1, tt2)
        gmst = erfa.gmst06(tt1, ut2, tt1, tt2)
        gst = erfa.gst06a(tt1, ut2, tt1, tt2)
        gmst82 = erfa.gmst82(tt1, ut2)
        eps = erfa.obl06(tt1, tt2)
        row = [tt1, tt2, ut2, xp, yp, dx, dy, x, y, s, sp, era, gmst, gst, gmst82, eps, dpsi, deps, dpsib, depsb]
        for m in (rc2t, rb, rp, rbp, rnpb):
            row += list(np.asarray(m).ravel())
        rows.append(row)
    mats = []
    for name in ("c2t", "rb", "rp", "rbp", "npb"):
        mats += [f"{name}{i}{j}" for i in range(3) for j in range(3)]
    header = ["tt1", "tt2", "ut12", "xp", "yp", "dx", "dy", "x", "y", "s", "sp", "era", "gmst06", "gst06a", "gmst82",
              "obl06", "dpsi06a", "deps06a", "dpsi00b", "deps00b"] + mats
    write_csv("frames.csv", header, rows, "ERFA precession-nutation and CIO-based GCRS->ITRS (UT1 jd1 = tt1)")


def astrometry_section():
    rng = random.Random(99)
    rows = []
    for (p, t, rh, wl) in [(1013.25, 15.0, 0.5, 0.574), (800.0, -10.0, 0.1, 0.55), (1030.0, 30.0, 0.9, 0.7),
                           (1000.0, 10.0, 0.5, 2000.0), (600.0, 0.0, 0.0, 1.0)]:
        a, b = erfa.refco(p, t, rh, wl)
        rows.append((p, t, rh, wl, a, b))
    write_csv("refco.csv", ["phpa", "tc", "rh", "wl", "refa", "refb"], rows, "ERFA refco")

    rows = []
    for _ in range(50):
        ra, dec = rng.uniform(0, 2 * np.pi), rng.uniform(-1.5, 1.5)
        l, b = erfa.icrs2g(ra, dec)
        rows.append((ra, dec, l, b))
    write_csv("galactic.csv", ["ra", "dec", "l", "b"], rows, "ERFA icrs2g")

    # ICRS -> observed for epochs inside the SPK fixture (2024-01-05 .. 2024-02-25).
    rows = []
    sites = [(-105.0 * erfa.DD2R, 40.0 * erfa.DD2R, 1600.0), (151.2 * erfa.DD2R, -33.9 * erfa.DD2R, 50.0),
             (10.0 * erfa.DD2R, 78.0 * erfa.DD2R, 0.0)]
    for i in range(120):
        elong, phi, hm = sites[i % 3]
        day = rng.uniform(4.0, 55.0)
        u1, u2 = erfa.dtf2d("UTC", 2024, 1, 1, 0, 0, 0.0)
        u2 += day
        rc, dc = rng.uniform(0, 2 * np.pi), rng.uniform(-1.4, 1.4)
        pr = rng.uniform(-1e-5, 1e-5)        # rad/yr (dRA/dt)
        pd = rng.uniform(-1e-5, 1e-5)
        px = rng.choice([0.0, rng.uniform(0.001, 0.8)])  # arcsec
        rv = rng.uniform(-50, 50)            # km/s
        dut1 = rng.uniform(-0.5, 0.5)
        xp = rng.uniform(-0.3, 0.3) * erfa.DAS2R
        yp = rng.uniform(0, 0.6) * erfa.DAS2R
        refr = i % 2
        phpa, tc, rh, wl = (1013.25, 15.0, 0.5, 0.574) if refr else (0.0, 0.0, 0.0, 0.574)
        aob, zob, hob, dob, rob, eo = erfa.atco13(rc, dc, pr, pd, px, rv, u1, u2, dut1, elong, phi, hm, xp, yp,
                                                  phpa, tc, rh, wl)
        rows.append((u1, u2, rc, dc, pr, pd, px, rv, dut1, elong, phi, hm, xp, yp, refr, aob, zob))
    write_csv("atco13.csv", ["utc1", "utc2", "rc", "dc", "pr", "pd", "px", "rv", "dut1", "elong", "phi", "hm", "xp",
                             "yp", "refraction", "aob", "zob"], rows,
              "ERFA atco13 ICRS(J2000)->observed; refraction=1 uses 1013.25 hPa, 15 C, 50%, 0.574 um")


SECTIONS = {"time": time_section, "geodesy": geodesy_section, "frames": frames_section,
            "astrometry": astrometry_section}

if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for name in (sys.argv[1:] or SECTIONS):
        SECTIONS[name]()
