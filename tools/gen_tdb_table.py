#!/usr/bin/env python3
"""Generate src/data/fairhead_tdb.cpp from ERFA's dtdb.c.

Usage: python3 tools/gen_tdb_table.py path/to/erfa/src/dtdb.c > src/data/fairhead_tdb.cpp

The Fairhead & Bretagnon (1990) TDB-TT series coefficients are taken from
ERFA (BSD-3-Clause, Copyright (C) 2013-2023 NumFOCUS Foundation, derived from
SOFA). See THIRD_PARTY_NOTICES.md.
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
body = src[src.index("fairhd[787][3]"):]
body = body[:body.index("};")]
rows = re.findall(r"\{\s*([-+0-9.eE]+)\s*,\s*([-+0-9.eE]+)\s*,\s*([-+0-9.eE]+)\s*\}", body)
if len(rows) != 787:
    sys.exit(f"expected 787 rows, found {len(rows)}")

print("""/**********************************************************************
 * fairhead_tdb.cpp  --  GENERATED by tools/gen_tdb_table.py, do not edit.
 *
 * Fairhead & Bretagnon (1990) TDB-TT series: 787 terms of
 *   amplitude (seconds), frequency (rad / Julian millennium), phase (rad).
 * Terms 0-473 multiply T^0, 474-678 T^1, 679-763 T^2, 764-783 T^3, 784-786 T^4.
 *
 * Coefficients from ERFA dtdb.c:
 *   Copyright (C) 2013-2023, NumFOCUS Foundation. All rights reserved.
 *   Derived, with permission, from the SOFA library.
 *   Redistributed under the BSD 3-Clause license; see THIRD_PARTY_NOTICES.md.
 **********************************************************************/

#include "fairhead_tdb.h"

namespace astro::detail {

const double kFairheadTdb[787][3] = {""")
for a, f, p in rows:
    print(f"    {{{a}, {f}, {p}}},")
print("""};

} // namespace astro::detail""")
