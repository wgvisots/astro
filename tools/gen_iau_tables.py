"""Generate src/data/iau2006_series.cpp from the IERS Conventions (2010) Chapter 5
tables and ERFA's nut00b.c.

Usage:
  python3 tools/gen_iau_tables.py IERS_DIR ERFA_NUT00B_C > src/data/iau2006_series.cpp

IERS_DIR must contain tab5.2a.txt, tab5.2b.txt, tab5.2d.txt, tab5.3a.txt and
tab5.3b.txt from https://iers-conventions.obspm.fr/content/chapter5/additional_info/
(IERS Technical Note 36). The IAU 2000B coefficients come from ERFA
(BSD-3-Clause, see THIRD_PARTY_NOTICES.md).
"""
import os
import re
import sys

NUM = r"[-+]?\d+\.?\d*(?:[eE][-+]?\d+)?"


def parse_poly(text):
    m = re.search(r"Polynomial part \(unit microarcsecond\)\s*\n\s*\n(.*)\n", text)
    line = m.group(1).replace(" ", "")
    # Terms like -16617.  +2004191898.t  -429782.9t^2
    terms = re.findall(r"([-+]?\d+\.?\d*)(t(?:\^(\d))?)?", line)
    coef = [0.0] * 6
    for val, tpart, power in terms:
        if val in ("", "+", "-"):
            continue
        p = 0 if not tpart else (int(power) if power else 1)
        coef[p] = float(val)
    return coef


def parse_series(text):
    """Return list of (power, [14 ints], sin_coef, cos_coef)."""
    terms = []
    power = None
    for line in text.splitlines():
        m = re.match(r"\s*j\s*=\s*(\d)\s+Number\s+of\s+terms\s*=\s*(\d+)", line)
        if m:
            power = int(m.group(1))
            continue
        if power is None:
            continue
        f = line.split()
        if len(f) == 17 and re.fullmatch(r"\d+", f[0]):
            terms.append((power, [int(x) for x in f[3:17]], float(f[1]), float(f[2])))
    return terms


def check_counts(text, terms, name):
    for m in re.finditer(r"j\s*=\s*(\d)\s+Number\s+of\s+terms\s*=\s*(\d+)", text):
        p, n = int(m.group(1)), int(m.group(2))
        got = sum(1 for t in terms if t[0] == p)
        if got != n:
            sys.exit(f"{name}: power {p}: expected {n} terms, parsed {got}")


def parse_nut00b(path):
    src = open(path, encoding="utf-8").read()
    body = src[src.index("} x[] = {"):]
    body = body[:body.index("};")]
    rows = re.findall(r"\{\s*(" + r"\s*,\s*".join([r"-?\d+"] * 5) + r")\s*,\s*(" +
                      r"\s*,\s*".join([NUM] * 6) + r")\s*\}", body)
    out = []
    for ints, floats in rows:
        out.append(([int(x) for x in ints.split(",")], [float(x) for x in floats.split(",")]))
    if len(out) != 77:
        sys.exit(f"nut00b: expected 77 rows, got {len(out)}")
    return out


def emit_series(name, terms):
    print(f"const SeriesTerm {name}[{len(terms)}] = {{")
    for power, n, s, c in terms:
        print(f"    {{{power}, {{{', '.join(str(x) for x in n)}}}, {s!r}, {c!r}}},")
    print("};")
    print(f"const std::size_t {name}Count = {len(terms)};\n")


def main():
    iers, nut00b = sys.argv[1], sys.argv[2]
    tabs = {}
    for t in ("tab5.2a", "tab5.2b", "tab5.2d", "tab5.3a", "tab5.3b"):
        tabs[t] = open(os.path.join(iers, t + ".txt"), encoding="latin-1").read()
    series = {}
    for t, text in tabs.items():
        series[t] = parse_series(text)
        check_counts(text, series[t], t)

    print("""/**********************************************************************
 * iau2006_series.cpp  --  GENERATED by tools/gen_iau_tables.py, do not edit.
 *
 * IAU 2006/2000A series from the IERS Conventions (2010), IERS Technical
 * Note 36, Chapter 5:
 *   Table 5.2a  CIP X       (IAU 2006 precession + IAU 2000A_R06 nutation)
 *   Table 5.2b  CIP Y
 *   Table 5.2d  s + XY/2
 *   Table 5.3a  nutation in longitude (IAU 2000_R06)
 *   Table 5.3b  nutation in obliquity (IAU 2000_R06)
 * Units: microarcseconds (per Julian century^power).
 * Fundamental-argument multipliers, in order:
 *   l, l', F, D, Om, L_Me, L_Ve, L_E, L_Ma, L_J, L_Sa, L_U, L_Ne, p_A
 *
 * IAU 2000B (77-term) luni-solar series from ERFA nut00b.c:
 *   Copyright (C) 2013-2023, NumFOCUS Foundation. All rights reserved.
 *   Derived, with permission, from the SOFA library.
 *   Redistributed under the BSD 3-Clause license; see THIRD_PARTY_NOTICES.md.
 *   Units: 0.1 microarcsecond.
 **********************************************************************/

#include "iau2006_series.h"

namespace astro::detail {
""")
    for name, t in (("kCipXPoly", "tab5.2a"), ("kCipYPoly", "tab5.2b"), ("kSXY2Poly", "tab5.2d")):
        c = parse_poly(tabs[t])
        print(f"const double {name}[6] = {{{', '.join(repr(x) for x in c)}}};")
    print()
    emit_series("kCipX", series["tab5.2a"])
    emit_series("kCipY", series["tab5.2b"])
    emit_series("kSXY2", series["tab5.2d"])
    emit_series("kNutLongitude", series["tab5.3a"])
    emit_series("kNutObliquity", series["tab5.3b"])

    rows = parse_nut00b(nut00b)
    print("const Nut2000BTerm kNut2000B[77] = {")
    for n, f in rows:
        print(f"    {{{{{', '.join(str(x) for x in n)}}}, {', '.join(repr(x) for x in f)}}},")
    print("};\n")
    print("} // namespace astro::detail")


if __name__ == "__main__":
    main()
